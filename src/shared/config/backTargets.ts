/*
 * Сюда намеренно не попали /activity, /manage и /moderation: они редиректят
 * на первый таб через replace, то есть даже не занимают запись в истории
 * и целью возврата стать не могут.
 *
 * Не попал и /login: возвращать на экран входа нельзя, такая запись уводит
 * пользователя из приложения. Для неё сработает фолбэк страницы.
 */

/** Совпадает ли адрес с шаблоном маршрута: сравниваем посегментно, `:id` — джокер. */
const matches = (pattern: string, path: string) => {
  const p = pattern.split('/')
  const a = path.split('/')
  return p.length === a.length && p.every((seg, i) => seg.startsWith(':') || seg === a[i])
}

/**
 * Название страницы по её адресу. `url` — путь вместе с хэшем, потому что
 * разделы «Моей платформы» различаются только хэшем.
 *
 * Вернёт null, если страницу возвращать некуда (вход, 404, редирект-раздел) —
 * вызывающий код в этом случае уходит на фолбэк.
 */
export const backLabel = (url: string): string | null => {
  const [path, hash] = [url.split('#')[0], url.includes('#') ? `#${url.split('#')[1]}` : '']
  const found = TARGETS.find(([pattern]) => {
    const [pPath, pHash] = [pattern.split('#')[0], pattern.includes('#') ? `#${pattern.split('#')[1]}` : '']
    return matches(pPath, path) && pHash === hash
  })
  return found ? found[1] : null
}
