import { ROUTES } from './routes'

/**
 * Названия страниц для кнопки «Назад». Единственное место, где живут эти
 * формулировки: подпись собирается как «Назад » + строка отсюда.
 *
 * Хранится хвост целиком, вместе с предлогом, — предлог зависит от названия
 * («в Мою платформу», но «к Моим проектам»), выводить его правилом нельзя.
 *
 * Заглавная только у первого слова названия: она показывает, где кончается
 * служебное «Назад к» и начинается имя страницы. Вторая заглавная внутри
 * названия разбивала бы его на две сущности вместо одной.
 */
const TARGETS: Array<[path: string, label: string]> = [
  // Порядок важен: выигрывает первое совпадение, поэтому вложенные пути
  // идут раньше своих разделов.
  [ROUTES.ACTIVITY.MY_PROJECTS, 'к Моим проектам'],
  [ROUTES.ACTIVITY.MY_APPLICATIONS, 'к Моим откликам'],
  [ROUTES.ACTIVITY.FAVORITES, 'к Понравившимся'],

  // От лэндинга отличается уточнением «платформы» в его подписи — здесь таб
  // называется ровно так, как написано на нём самом.
  [ROUTES.MANAGE.PROJECTS, 'ко Всем проектам'],
  [ROUTES.MANAGE.TEAMS, 'к Откликам и команде'],
  [ROUTES.MANAGE.GRADES, 'к Оценке участников'],

  [ROUTES.MODERATION.PROJECTS, 'к Модерации проектов'],
  [ROUTES.MODERATION.COMPLAINTS, 'ко Входящим жалобам'],

  [ROUTES.PROJECTS.CREATE, 'к Созданию проекта'],
  [ROUTES.PROJECTS.RECRUITMENT, 'к Проектам в наборе'],
  [ROUTES.PROJECTS.IN_PROGRESS, 'к Проектам в работе'],
  [ROUTES.PROJECTS.PROJECT, 'к Проекту'],
  // Страницы ещё нет — /projects редиректит на набор, поэтому подпись спит.
  // TODO: название временное, дизайнер вернётся с финальным. Уточнение «платформы»
  // нужно, чтобы не совпадать с табом «Все проекты» в управлении проектами.
  [ROUTES.PROJECTS.BASE, 'ко Всем проектам платформы'],

  [ROUTES.PROFILE.BY_ID, 'к профилю студента'],
  [ROUTES.PROFILE.BASE, 'в Мой профиль'],

  // Страницы уведомлений ещё нет ни в роутере, ни в ROUTES — строка из дерева
  // страниц лежит заранее, чтобы при её появлении кнопку не пришлось трогать.
  ['/notifications', 'к Уведомлениям'],

  [ROUTES.MAIN, 'в Мою платформу']
]

/*
 * Сюда намеренно не попали /activity, /manage и /moderation: они редиректят
 * на первый таб через replace, то есть даже не занимают запись в истории
 * и целью возврата стать не могут.
 *
 * Не попал и /login: возвращать на экран входа нельзя, такая запись уводит
 * пользователя из приложения. Для неё сработает фолбэк страницы.
 */

/** Совпадает ли адрес с шаблоном маршрута: сравниваем посегментно, `:id` — джокер. */
const matches = (pattern: string, path: string) => {
  const p = pattern.split('/')
  const a = path.split('/')
  return p.length === a.length && p.every((seg, i) => seg.startsWith(':') || seg === a[i])
}

/**
 * Название страницы по её адресу. `url` — путь вместе с хэшем, потому что
 * разделы «Моей платформы» различаются только хэшем.
 *
 * Вернёт null, если страницу возвращать некуда (вход, 404, редирект-раздел) —
 * вызывающий код в этом случае уходит на фолбэк.
 */
export const backLabel = (url: string): string | null => {
  const [path, hash] = [url.split('#')[0], url.includes('#') ? `#${url.split('#')[1]}` : '']
  const found = TARGETS.find(([pattern]) => {
    const [pPath, pHash] = [pattern.split('#')[0], pattern.includes('#') ? `#${pattern.split('#')[1]}` : '']
    return matches(pPath, path) && pHash === hash
  })
  return found ? found[1] : null
}
